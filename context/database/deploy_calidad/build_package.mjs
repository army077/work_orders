const literal = value => "'" + value.replaceAll("'", "''") + "'";
const array = values => `ARRAY[${values.map(literal).join(',')}]::text[]`;
export function statements(sql) {
  // The reused snapshot has standard quoted strings, identifiers and line comments.
  const result = []; let current = '', quoted = false, identifier = false, comment = false;
  for (let i = 0; i < sql.length; i++) {
    const c = sql[i], next = sql[i + 1];
    if (comment) { if (c === '\n') { comment = false; current += c; } continue; }
    if (!quoted && !identifier && c === '-' && next === '-') { comment = true; i++; continue; }
    current += c;
    if (!identifier && c === "'") {
      if (quoted && next === "'") { current += next; i++; } else quoted = !quoted;
    } else if (!quoted && c === '"') {
      if (identifier && next === '"') { current += next; i++; } else identifier = !identifier;
    } else if (!quoted && !identifier && c === ';') { result.push(current.slice(0, -1).trim()); current = ''; }
  }
  if (quoted || identifier) throw new Error('SQL_UNTERMINATED');
  if (current.trim()) result.push(current.trim());
  return result;
}
function header(database) {
  return `-- GENERATED by build_package.mjs; HeidiSQL / PostgreSQL 16. No psql commands.
BEGIN ISOLATION LEVEL REPEATABLE READ READ ONLY;
-- Wrong database/version aborts the transaction before catalog/data capture.
SELECT 1 / (coalesce(current_database() = '${database}' AND
  current_setting('server_version_num')::int / 10000 = 16, false)::int) AS database_guard;
SET LOCAL search_path = pg_catalog;
SET LOCAL statement_timeout = '120s';
SET LOCAL lock_timeout = '5s';
SET LOCAL row_security = off;
SET LOCAL timezone = 'UTC';
`;
}
const hash = expression => `('sha256:' || encode(sha256(convert_to((${expression})::text,'UTF8')),'hex'))`;
function baselineCapture() {
  let sql = readFileSync(new URL('../transfer_calidad/snapshot.sql', import.meta.url), 'utf8');
  sql = sql.replace(/SELECT 1 \/ \(\(NOT EXISTS[\s\S]*?\\gset/, '');
  // Scope truthfully reports excluded historical presence, but never selects it.
  sql = sql.replace(/'name', name, 'present', to_regclass\(name\) IS NOT NULL\)/,
    `'name', name, 'present', to_regclass(name) IS NOT NULL, 'selected', name = ANY(${array(core)}))`);
  sql = sql.replaceAll(":'core_tables'::text[] || :'historical_tables'::text[]", array(core));
  // The scope alone includes all inventory entries, including pending historicals.
  sql = sql.replace(/FROM unnest\(ARRAY\[[^\n]+\]::text\[\]\) t\(name\);\s*\n\s*-- Catalogo/,
    `FROM unnest(${array([...core, ...historical])}) t(name);\n-- Catalogo`);
  sql = sql.replaceAll(":'root_functions'::text[]", array(rootFunctions));
  // Never count a view/foreign table or expand inherited children while reporting NO-GO.
  const readable = `(SELECT c.oid FROM pg_class c WHERE c.relkind='r' AND NOT c.relrowsecurity AND NOT c.relforcerowsecurity)`;
  sql = sql.replaceAll('SELECT to_regclass(name) AS oid',
    `SELECT CASE WHEN to_regclass(name) IN ${readable} THEN to_regclass(name) END AS oid`);
  sql = sql.replaceAll('WHERE to_regclass(name) IS NOT NULL', `WHERE to_regclass(name) IN ${readable}`);
  sql = sql.replace(/^\\gexec\s*$/gm, ';').replace(/^\\[^\n]*$/gm, '');
  sql = sql.replace(/^BEGIN[^;]*;/m, '').replace(/ROLLBACK;/g, '');
  // Shareable evidence: compare hashes instead of exporting bodies or literal defaults.
  for (const expression of ['pg_get_functiondef(p.oid)', 'pg_get_constraintdef(oid, true)',
    'pg_get_indexdef(i.indexrelid)', 'pg_get_triggerdef(oid, true)', 'pg_get_ruledef(oid, true)',
    'pg_get_expr(d.adbin, d.adrelid)', 'pg_get_expr(polqual, polrelid)', 'pg_get_expr(polwithcheck, polrelid)']) {
    sql = sql.replaceAll(expression, hash(expression));
  }
  return statements(sql).map(query => {
    if (!query.includes('SELECT format(')) return `SELECT q.jsonb_build_object AS record FROM (\n${query}\n) q`;
    if (query.includes("''kind'', ''count''")) query=query.replace(' FROM %s;', ' FROM ONLY %s;');
    if (query.includes("''kind'', ''fk_rows''")) query=query.replace(' FROM %s c WHERE', ' FROM ONLY %s c WHERE')
      .replace('AND NOT EXISTS (SELECT FROM ', 'AND NOT EXISTS (SELECT FROM ONLY ');
    return `SELECT x.payload::jsonb AS record FROM (\n${query}\n) g(sql)
CROSS JOIN LATERAL XMLTABLE('/table/row' PASSING query_to_xml(
  'SELECT q.jsonb_build_object::text AS payload FROM (' || rtrim(g.sql, ';') || ') q',
  false, false, '') COLUMNS payload text PATH 'payload') x`;
  }).join('\nUNION ALL\n');
}
// A sequence consumer can be demonstrated by ownership or an actual default dependency.
const consumers = `consumers AS (
 SELECT d.objid AS sequence_oid, d.refobjid AS table_oid, d.refobjsubid AS attnum
 FROM pg_depend d JOIN pg_class s ON s.oid=d.objid AND s.relkind='S'
 WHERE d.classid='pg_class'::regclass AND d.refclassid='pg_class'::regclass AND d.deptype IN ('a','i')
 UNION
 SELECT d.refobjid,a.adrelid,a.adnum FROM pg_attrdef a JOIN pg_depend d
 ON d.classid='pg_attrdef'::regclass AND d.objid=a.oid AND d.refclassid='pg_class'::regclass
 JOIN pg_class s ON s.oid=d.refobjid AND s.relkind='S'
)`;
// Extension membership is catalog evidence, never a schema/name allowlist.
// Internal implementation objects (e.g. an automatically created array type)
// inherit membership. Normal, auto and auto-extension dependencies do NOT.
export const extensionCatalog = `installed_extensions AS (
 SELECT e.oid,e.extname AS name,n.nspname AS schema,e.extversion AS version
 FROM pg_extension e JOIN pg_namespace n ON n.oid=e.extnamespace
), extension_members(classid,objid,extension_oid) AS (
 -- Only extension membership ('e') and internal implementation ('i') are infrastructure.
 -- A normal dependency on an extension type/function does not imply membership.
 SELECT d.classid,d.objid,e.oid FROM pg_depend d JOIN installed_extensions e ON e.oid=d.refobjid
 WHERE d.refclassid='pg_extension'::regclass AND d.deptype='e' AND d.objsubid=0 AND d.refobjsubid=0
 UNION
 SELECT d.classid,d.objid,m.extension_oid FROM extension_members m JOIN pg_depend d
 ON d.refclassid=m.classid AND d.refobjid=m.objid
 WHERE d.deptype='i' AND d.objsubid=0 AND d.refobjsubid=0
), extension_infrastructure AS (
 SELECT 'pg_extension'::regclass::oid AS classid,oid AS objid,oid AS extension_oid FROM installed_extensions
 UNION SELECT classid,objid,extension_oid FROM extension_members
)`;
const extensionReport = `SELECT 1,'EXTENSION_INFRA','INFO',
 jsonb_build_object('kind','extension','name',name,'schema',schema,'version',version) FROM installed_extensions`;
function dependencyIssues() {
  // Reuse the already audited outgoing catalog closure, not a second traversal.
  let sql=readFileSync(new URL('../transfer_calidad/dependencies.sql',import.meta.url),'utf8');
  sql=sql.replace(/^\\[^\n]*$/gm,'').replaceAll(":'core_tables'::text[] || :'historical_tables'::text[]",array(core))
    .replaceAll(":'root_functions'::text[]",array(rootFunctions));
  const query=statements(sql).find(s=>s.startsWith('WITH RECURSIVE'));
  const prefix=query.slice(0,query.indexOf("SELECT jsonb_build_object('kind', 'object_dependency'"));
  return prefix + `SELECT 'UNSUPPORTED_DEPENDENCY:'||i.type||':'||coalesce(i.schema,'')||':'||coalesce(i.name,'') AS detail
FROM closure c CROSS JOIN LATERAL pg_identify_object(c.classid,c.objid,0) i
WHERE NOT coalesce((
 coalesce(i.schema,'')='pg_catalog' OR
 (c.classid='pg_namespace'::regclass AND c.objid IN ('public'::regnamespace,'pg_catalog'::regnamespace)) OR
 (c.classid='pg_language'::regclass AND c.objid IN (SELECT oid FROM pg_language WHERE lanname IN ('internal','c','sql','plpgsql'))) OR
 EXISTS(SELECT FROM extension_infrastructure e WHERE e.classid=c.classid AND e.objid=c.objid) OR
 (c.classid='pg_class'::regclass AND c.objid IN (
   SELECT to_regclass(record->>'name') FROM capture WHERE record->>'kind' IN ('table','sequence')
   UNION SELECT indexrelid FROM pg_index WHERE indrelid IN (SELECT oid FROM selected))) OR
 (c.classid='pg_type'::regclass AND c.objid IN (SELECT t.oid FROM pg_type t LEFT JOIN pg_type e ON e.oid=t.typelem
   WHERE t.typrelid IN (SELECT oid FROM selected) OR e.typrelid IN (SELECT oid FROM selected))) OR
 (c.classid='pg_proc'::regclass AND c.objid IN (SELECT p.oid FROM pg_proc p WHERE p.oid::regprocedure::text IN
   (SELECT record->>'name' FROM capture WHERE record->>'kind'='function'))) OR
 (c.classid='pg_attrdef'::regclass AND c.objid IN (SELECT oid FROM pg_attrdef WHERE adrelid IN (SELECT oid FROM selected))) OR
 (c.classid='pg_constraint'::regclass AND c.objid IN (SELECT oid FROM pg_constraint WHERE conrelid IN (SELECT oid FROM selected))) OR
 (c.classid='pg_trigger'::regclass AND c.objid IN (SELECT oid FROM pg_trigger WHERE tgrelid IN (SELECT oid FROM selected)))
),false)`;
}
function captureSQL(database) {
  const final = database === 'artecnologia' ? 'ORIGEN_APTO' : 'CAPTURA_RESTORE_APTA';
  return header(database) + `WITH RECURSIVE ${extensionCatalog}, ${consumers},
capture AS MATERIALIZED (
${baselineCapture()}
), selected AS (SELECT to_regclass(t) AS oid FROM unnest(${array(core)}) t),
sequence_checks AS MATERIALIZED (
 SELECT r.record->>'name' AS name, c.table_oid, a.attname AS consumer_column,
 c.table_oid::regclass::text AS consumer_table,
 CASE WHEN q.seqcache<>1 OR q.seqcycle OR q.seqincrement=0 OR
   (SELECT count(*) FROM consumers c2 WHERE c2.sequence_oid=s.oid)<>1 OR
   c.table_oid NOT IN (SELECT oid FROM selected) OR c.table_oid IS NULL OR
   a.atttypid NOT IN ('int2'::regtype,'int4'::regtype,'int8'::regtype,'numeric'::regtype)
 THEN false ELSE
   (r.record->>'last_value')::numeric + CASE WHEN (r.record->>'is_called')::boolean THEN q.seqincrement ELSE 0 END
     BETWEEN q.seqmin AND q.seqmax AND
   CASE WHEN q.seqincrement>0 THEN
     m.maximum IS NULL OR (r.record->>'last_value')::numeric + CASE WHEN (r.record->>'is_called')::boolean THEN q.seqincrement ELSE 0 END > m.maximum::numeric
   ELSE m.minimum IS NULL OR (r.record->>'last_value')::numeric + CASE WHEN (r.record->>'is_called')::boolean THEN q.seqincrement ELSE 0 END < m.minimum::numeric END
 END AS safe
 FROM capture r JOIN pg_class s ON s.oid=to_regclass(CASE WHEN r.record->>'kind'='sequence' THEN r.record->>'name' END)
 JOIN pg_sequence q ON q.seqrelid=s.oid
 LEFT JOIN consumers c ON c.sequence_oid=s.oid
 LEFT JOIN pg_attribute a ON a.attrelid=c.table_oid AND a.attnum=c.attnum
 LEFT JOIN LATERAL XMLTABLE('/table/row' PASSING query_to_xml(
   CASE WHEN c.table_oid IN (SELECT oid FROM selected) AND a.atttypid IN
   ('int2'::regtype,'int4'::regtype,'int8'::regtype,'numeric'::regtype)
   THEN format('SELECT min(%I)::text AS minimum,max(%I)::text AS maximum FROM ONLY %s',a.attname,a.attname,c.table_oid::regclass)
   ELSE 'SELECT NULL::text AS minimum,NULL::text AS maximum' END,
   false,false,'') COLUMNS minimum text PATH 'minimum',maximum text PATH 'maximum') m ON true
 WHERE r.record->>'kind'='sequence'
), dependency_issues AS (${dependencyIssues()}), issues AS (
 SELECT detail FROM dependency_issues
 UNION ALL SELECT 'UNSUPPORTED_RULE_POLICY:'||c.oid::regclass::text FROM pg_class c WHERE c.oid IN (SELECT oid FROM selected)
 AND (EXISTS(SELECT FROM pg_rewrite WHERE ev_class=c.oid) OR EXISTS(SELECT FROM pg_policy WHERE polrelid=c.oid))
 UNION ALL SELECT 'EVENT_TRIGGER' FROM pg_event_trigger
 UNION ALL SELECT 'UNSUPPORTED_SEQUENCE_IDENTIFIER:'||(record->>'name') FROM capture
 WHERE record->>'kind'='sequence' AND record->>'name' !~ '^public[.][a-z_][a-z0-9_]*$'
 UNION ALL SELECT 'UNSUPPORTED_FUNCTION_NAMESPACE:'||(record->>'name') FROM capture
 WHERE record->>'kind'='function' AND record->>'name' NOT LIKE 'public.%'
 UNION ALL SELECT 'DATABASE_ROLE_SETTINGS_REQUIRE_REVIEW' FROM pg_db_role_setting WHERE
 setdatabase IN (0,(SELECT oid FROM pg_database WHERE datname=current_database()))
 UNION ALL
 SELECT 'MISSING_OR_UNSUPPORTED_TABLE:'||t AS detail FROM unnest(${array(core)}) t
 LEFT JOIN pg_class c ON c.oid=to_regclass(t)
 WHERE c.oid IS NULL OR c.relkind<>'r' OR c.relrowsecurity OR c.relforcerowsecurity
 UNION ALL SELECT 'INHERITANCE' FROM pg_inherits WHERE inhrelid IN (SELECT oid FROM selected) OR inhparent IN (SELECT oid FROM selected)
 UNION ALL SELECT 'LOGISTICS_ALREADY_PRESENT:'||t FROM unnest(${array(logistics)}) t WHERE to_regclass(t) IS NOT NULL
 UNION ALL SELECT 'OUTBOUND_FK:'||conrelid::regclass::text||'.'||conname FROM pg_constraint
 WHERE contype='f' AND conrelid IN (SELECT oid FROM selected) AND confrelid NOT IN (SELECT oid FROM selected)
 UNION ALL SELECT 'UNSAFE_SEQUENCE:'||name FROM sequence_checks WHERE safe IS DISTINCT FROM true
 UNION ALL SELECT 'MISSING_FUNCTION:'||t FROM unnest(${array(rootFunctions)}) t
 WHERE NOT EXISTS (SELECT FROM capture WHERE record->>'kind'='function' AND record->>'name' LIKE 'public.'||t||'(%')
 UNION ALL SELECT 'INVALID_FK:'||(record->>'name') FROM capture
 WHERE record->>'kind'='fk_rows' AND (record->>'violations'<>'0' OR record->>'validated'<>'true')
 UNION ALL SELECT 'INVALID_CONSTRAINT:'||(record->>'name') FROM capture,
 LATERAL jsonb_array_elements(record->'constraints') v WHERE record->>'kind'='table' AND v->>'validated'<>'true'
 UNION ALL SELECT 'INVALID_INDEX:'||(record->>'name') FROM capture,
 LATERAL jsonb_array_elements(record->'indexes') v WHERE record->>'kind'='table' AND (v->>'valid'<>'true' OR v->>'ready'<>'true')
), report AS (
 SELECT 0 AS position,'IDENTIDAD'::text AS "CHECK",'INFO'::text AS "ESTADO",
 jsonb_build_object('database',current_database(),'version',current_setting('server_version'),
 'timezone',current_setting('TimeZone'),'current_user',current_user) AS "DETALLE"
 UNION ALL ${extensionReport}
 UNION ALL SELECT 1,'TABLA:'||t,CASE WHEN to_regclass(t) IS NULL THEN 'NO' ELSE 'SI' END,
 jsonb_build_object('name',t,'exists',to_regclass(t) IS NOT NULL,'rows',
 (SELECT record->>'count' FROM capture WHERE record->>'kind'='count' AND record->>'name'=t)) FROM unnest(${array(core)}) t
 UNION ALL SELECT 2,'HISTORICO:'||t,'PENDIENTE_VERIFICACION_PROD',
 jsonb_build_object('name',t,'exists',to_regclass(t) IS NOT NULL,'selected',false) FROM unnest(${array(historical)}) t
 UNION ALL SELECT 3,'SECUENCIA:'||name,CASE WHEN safe THEN 'SI' ELSE 'REVISAR' END,
 jsonb_build_object('name',name,'consumer_table',consumer_table,'consumer_column',consumer_column,'safe_next',safe) FROM sequence_checks
 UNION ALL SELECT 4,'DEPENDENCIA','REVISAR',jsonb_build_object('reason',detail) FROM issues
 UNION ALL SELECT 4,'FUNCION_TOC','METADATO',jsonb_build_object('catalog', 'pg_proc'::regclass::oid,'oid',p.oid)
 FROM pg_proc p WHERE p.oid::regprocedure::text IN (SELECT record->>'name' FROM capture WHERE record->>'kind'='function')
 UNION ALL SELECT 4,'OBJETO_TOC','METADATO',jsonb_build_object('catalog',o.catalog,'oid',o.oid)
 FROM (
 SELECT 'pg_class'::regclass::oid AS catalog,oid FROM selected WHERE oid IS NOT NULL
 UNION SELECT 'pg_class'::regclass::oid,indexrelid FROM pg_index WHERE indrelid IN (SELECT oid FROM selected)
 UNION SELECT 'pg_class'::regclass::oid,to_regclass(record->>'name') FROM capture WHERE record->>'kind'='sequence'
 UNION SELECT 'pg_constraint'::regclass::oid,oid FROM pg_constraint WHERE conrelid IN (SELECT oid FROM selected)
 UNION SELECT 'pg_attrdef'::regclass::oid,oid FROM pg_attrdef WHERE adrelid IN (SELECT oid FROM selected)
 UNION SELECT 'pg_trigger'::regclass::oid,oid FROM pg_trigger WHERE tgrelid IN (SELECT oid FROM selected) AND NOT tgisinternal
 ) o
 UNION ALL SELECT 5,'CAPTURA','METADATO',record FROM capture WHERE record->>'kind'<>'complete'
 UNION ALL SELECT 6,'CAPTURA','METADATO',record FROM capture WHERE record->>'kind'='complete'
 UNION ALL SELECT 7,'${final}',CASE WHEN EXISTS(SELECT FROM issues) THEN '${database === 'artecnologia' ? 'REVISAR' : 'NO'}' ELSE 'SI' END,
 jsonb_build_object('issues',(SELECT count(*) FROM issues),'comparison_required',${database === 'calidad'})
) SELECT "CHECK","ESTADO","DETALLE" FROM report ORDER BY position,"CHECK", "DETALLE"->>'kind',"DETALLE"->>'name';
ROLLBACK;
`;
}
function emptySQL() {
  return header('calidad') + `WITH RECURSIVE ${extensionCatalog}, objects AS (
 SELECT 'pg_class'::regclass::oid AS classid,c.oid AS objid,'relation' AS kind,n.nspname AS schema,c.relname AS name FROM pg_class c
 JOIN pg_namespace n ON n.oid=c.relnamespace
 WHERE n.nspname NOT IN ('pg_catalog','information_schema') AND n.nspname !~ '^pg_toast|^pg_temp_'
 UNION ALL SELECT 'pg_proc'::regclass::oid,p.oid,'routine',n.nspname,p.oid::regprocedure::text FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace
 WHERE n.nspname NOT IN ('pg_catalog','information_schema') AND n.nspname !~ '^pg_toast|^pg_temp_'
 UNION ALL SELECT 'pg_trigger'::regclass::oid,t.oid,'trigger',n.nspname,t.tgname FROM pg_trigger t JOIN pg_class c ON c.oid=t.tgrelid
 JOIN pg_namespace n ON n.oid=c.relnamespace WHERE NOT t.tgisinternal AND n.nspname NOT IN ('pg_catalog','information_schema')
 UNION ALL SELECT 'pg_type'::regclass::oid,t.oid,'type',n.nspname,t.typname FROM pg_type t JOIN pg_namespace n ON n.oid=t.typnamespace
 WHERE n.nspname NOT IN ('pg_catalog','information_schema') AND n.nspname !~ '^pg_toast|^pg_temp_'
 UNION ALL SELECT 'pg_extension'::regclass::oid,oid,'extension',schema,name FROM installed_extensions
), classified_objects AS (
 SELECT o.*,e.extension_oid,x.name AS extension,x.schema AS extension_schema,x.version AS extension_version
 FROM objects o LEFT JOIN extension_infrastructure e ON e.classid=o.classid AND e.objid=o.objid
 LEFT JOIN installed_extensions x ON x.oid=e.extension_oid
), application_objects AS (
 SELECT * FROM classified_objects WHERE extension_oid IS NULL
), report AS (
 SELECT 0 AS position,'IDENTIDAD'::text AS "CHECK",'INFO'::text AS "ESTADO",jsonb_build_object(
 'database',current_database(),'version',current_setting('server_version'),'current_user',current_user,
 'address',host(inet_server_addr()),'port',inet_server_port(),
 'timezone',current_setting('TimeZone')) AS "DETALLE"
 UNION ALL ${extensionReport}
 UNION ALL SELECT 1,'EXTENSION_INFRA','INFO',to_jsonb(classified_objects) FROM classified_objects
 WHERE extension_oid IS NOT NULL AND kind<>'extension'
 UNION ALL SELECT 1,'OBJETO_INESPERADO','NO',to_jsonb(application_objects) FROM application_objects
 UNION ALL SELECT 2,'LEDGER',CASE WHEN to_regclass('public.logistica_schema_migrations') IS NULL THEN 'AUSENTE' ELSE 'NO' END,'{}'::jsonb
 UNION ALL SELECT 3,'DESTINO_VACIO_Y_APTO',CASE WHEN EXISTS(SELECT FROM application_objects)
 OR to_regclass('public.logistica_schema_migrations') IS NOT NULL THEN 'NO' ELSE 'SI' END,
 jsonb_build_object('unexpected_objects',(SELECT count(*) FROM application_objects),
 'unexpected_application_objects',(SELECT count(*) FROM application_objects),
 'application_objects',(SELECT count(*) FROM application_objects),
 'extension_objects',(SELECT count(*) FROM classified_objects WHERE extension_oid IS NOT NULL))
) SELECT "CHECK","ESTADO","DETALLE" FROM report ORDER BY position,"CHECK";
ROLLBACK;
`;
}
function logisticsSQL() {
  const files = artifacts();
  const expected = files.map((f,i) => `(${i+1},${literal(f.name)},${literal(f.sha256)})`).join(',\n');
  const shape = shapeSql.replace('$1::text', "'public'::text").trim().replace(/;$/, '');
  return header('calidad') + `WITH expected(position,name,hash) AS (VALUES ${expected}),
actual_shape AS (${shape}),
ledger AS MATERIALIZED (
 SELECT x.name,x.hash,x.applied_at::timestamptz AS applied_at FROM XMLTABLE('/table/row' PASSING query_to_xml(
 CASE WHEN to_regclass('public.logistica_schema_migrations') IS NULL THEN
 'SELECT NULL::text AS name,NULL::text AS hash,NULL::text AS applied_at WHERE false' ELSE
 'SELECT migration_name AS name,migration_sha256 AS hash,applied_at::text AS applied_at FROM public.logistica_schema_migrations' END,
 false,false,'') COLUMNS name text PATH 'name',hash text PATH 'hash',applied_at text PATH 'applied_at') x
), checks AS (
 SELECT 'SCHEMA_FINGERPRINT' AS name,fingerprint=${literal(states().at(-1).fingerprint)} AS ok,
 jsonb_build_object('fingerprint',fingerprint,'expected',${literal(states().at(-1).fingerprint)}) AS detail FROM actual_shape
 UNION ALL SELECT 'TABLA:'||t,to_regclass(t) IS NOT NULL,jsonb_build_object('table',t) FROM unnest(${array(logistics)}) t
 UNION ALL SELECT 'LEDGER', (SELECT count(*) FROM ledger)=7 AND NOT EXISTS (
 SELECT FROM expected e FULL JOIN ledger l ON l.name=e.name WHERE e.name IS NULL OR l.name IS NULL OR l.hash IS DISTINCT FROM e.hash
 ) AND NOT EXISTS (SELECT FROM expected a JOIN ledger x ON x.name=a.name
 JOIN expected b ON b.position>a.position JOIN ledger y ON y.name=b.name WHERE x.applied_at>=y.applied_at),
 jsonb_build_object('rows',(SELECT count(*) FROM ledger),'validation','expected_sha256_and_strict_applied_at_order')
), report AS (
 SELECT 0 AS position,name AS "CHECK",CASE WHEN ok THEN 'SI' ELSE 'NO' END AS "ESTADO",detail AS "DETALLE" FROM checks
 UNION ALL SELECT 1,'LOGISTICA_SCHEMA_VALIDO',CASE WHEN bool_and(ok) THEN 'SI' ELSE 'NO' END,'{}'::jsonb FROM checks
) SELECT "CHECK","ESTADO","DETALLE" FROM report ORDER BY position,"CHECK";
ROLLBACK;
`;
}
export function generatedFiles() {
  const dirs=['routes','services','repositories','auth','integrations'];
  const runtime=['db.js','server.js','package.json','package-lock.json','.npmrc','scripts/audit_node18_engines.cjs', ...dirs.flatMap(dir =>
    readdirSync(new URL(`../../api10/${dir}/`,import.meta.url)).filter(n=>n.endsWith('.js')).sort().map(n=>dir+'/'+n))];
  return new Map([
    ['01_preflight_artecnologia.sql',captureSQL('artecnologia')],
    ['02_preflight_calidad.sql',emptySQL()],
    ['03_validar_post_restore_calidad.sql',captureSQL('calidad')],
    ['04_validar_post_logistica_calidad.sql',logisticsSQL()],
    ['07_ARCHIVOS_API10_FILEZILLA.txt',runtime.join('\n')+'\n'],
  ].map(([name,bytes])=>[name,bytes.replaceAll('\r\n','\n')]));
}
if (process.argv[1] && import.meta.url===pathToFileURL(process.argv[1]).href) {
  for (const [name,bytes] of generatedFiles()) writeFileSync(new URL(name,import.meta.url),bytes);
}
